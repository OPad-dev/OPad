def glyph(ch):
    return GLYPHS[ch]


def text_width(s, height):
    """Width in mm of ``s`` rendered at cap height ``height``."""
    if not s:
        return 0.0
    return len(s) * ADVANCE * (height / CAP)


def strokes(s, x, y, height, mirror=False, anchor="center"):
    """Polylines (in mm) for ``s``, as a list of lists of (x, y) points.

    ``y`` is the vertical centre of the cap height, matching how KiCad places
    text.  ``mirror`` negates X about the anchor, which is what a bottom-layer
    (B.SilkS / B.Cu) text needs so it reads correctly through the board.
    """
    scale = height / CAP
    width = text_width(s, height)
    if anchor == "center":
        x0 = x - width / 2.0
    elif anchor == "left":
        x0 = x
    elif anchor == "right":
        x0 = x - width
    else:
        raise ValueError("anchor must be center, left or right: %r" % anchor)
    y0 = y - height / 2.0

    out = []
    pen = x0
    for ch in s:
        for poly in glyph(ch):
            pts = [(pen + px * scale, y0 + py * scale) for px, py in poly]
            out.append(pts)
        pen += ADVANCE * scale

    if mirror:
        axis = 2.0 * x if anchor == "center" else 2.0 * (x0 + width / 2.0)
        out = [[(axis - px, py) for px, py in poly] for poly in out]
    return out
